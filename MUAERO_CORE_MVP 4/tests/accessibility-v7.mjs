import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {parseOSM,combine,toXY} from '../src/data.js';
import {buildGraph,findRoute} from '../src/routing.js';
import {findBuildingApproach,nearestWalkable} from '../src/approach.js';
import {assess} from '../src/accessibility.js';
const a=JSON.parse(readFileSync(new URL('../data/campus_paths.json',import.meta.url)));
const b=JSON.parse(readFileSync(new URL('../data/campus_buildings.json',import.meta.url)));
const data=combine(parseOSM(a),parseOSM(b,{includePaths:false}));
assert.equal(data.ways.length,928);assert.equal(data.buildings.length,1422);
const graph=buildGraph(data);
const start=data.places.find(x=>x.name==='경영대 2호관');
const end=data.places.find(x=>x.name==='중앙도서관');
assert(start&&end);
assert.throws(()=>findRoute(graph,start,end,{maxSnap:0.5}),/보행로/);
const startApproach=findBuildingApproach(data,graph,start);const endApproach=findBuildingApproach(data,graph,end);
assert.equal(startApproach.kind,'near-building');assert.equal(endApproach.kind,'near-building');
const route=findRoute(graph,startApproach.point,endApproach.point);
assert(route.length>100&&route.length<1600);
assert(route.unknownMeters>0&&route.unknownMeters<=route.length+1);
assert(route.edgeSegments.length===route.links.length);
assert(!route.edgeSegments.some(x=>['stairs','road','shared'].includes(x.category)));
assert.throws(()=>findBuildingApproach(data,buildGraph(data,{verifiedOnly:true}),end,[],{verifiedOnly:true}),/출입구/);
const crossing=data.ways.find(x=>x.tags?.footway==='crossing');
const review={type:'crossing',status:'field_checked',note:'현장 조사 근거 테스트용 기록입니다.',width:'1.5',incline:'2%',surface:'concrete',kerbStart:'lowered'};
assert(!assess(crossing,{reviews:{[crossing.id]:review}}).verified);
review.kerbEnd='flush';assert(assess(crossing,{reviews:{[crossing.id]:review}}).verified);
const noRoad=graph.segments.find(x=>x.category==='stairs');assert(noRoad&&!noRoad.active);
console.log(`PASS v7: paths ${data.ways.length}, buildings ${data.buildings.length}, route ${route.length.toFixed(1)}m, unknown ${route.unknownMeters.toFixed(1)}m; approach ${startApproach.snapDistance.toFixed(1)}/${endApproach.snapDistance.toFixed(1)}m`);

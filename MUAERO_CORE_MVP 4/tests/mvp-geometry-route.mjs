import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as THREE from '../vendor/three.module.js';
import {parseOSM,combine,toXY} from '../src/data.js';
import {CampusRenderer} from '../src/renderer.js';
import {buildGraph,findRoute} from '../src/routing.js';

const read=p=>JSON.parse(fs.readFileSync(new URL(p,import.meta.url),'utf8'));
const data=combine(parseOSM(read('../data/campus_paths.json'),{includeBuildings:false}),parseOSM(read('../data/campus_buildings.json'),{includePaths:false}));
const r=Object.create(CampusRenderer.prototype);r.world=new THREE.Group();r.routeGroup=new THREE.Group();r.markerGroup=new THREE.Group();r.reportGroup=new THREE.Group();r.selectionGroup=new THREE.Group();r.start=null;r.end=null;r.terrain=null;
r.load(data);assert.equal(r.audit.renderedBuildings,1422);assert.equal(r.buildingTriangles.length,1422);
const last=r.buildingTriangles.at(-1);assert.ok(last.last>last.first);
const b=data.buildings.find(x=>x.name==='중앙도서관');assert.ok(b);
r.setSelectedBuilding(b.id);assert.equal(r.selectionGroup.children.length,1);
const entry=r.buildingTriangles.find(x=>x.building.id===b.id),position=r.buildingMesh.geometry.getAttribute('position');
const verts=[0,1,2].map(i=>new THREE.Vector3().fromBufferAttribute(position,entry.first*3+i));
const target=verts.reduce((a,p)=>a.add(p),new THREE.Vector3()).multiplyScalar(1/3);
r.camera=new THREE.PerspectiveCamera(60,1,.1,1000);r.camera.position.copy(target).add(new THREE.Vector3(0,60,0));r.camera.lookAt(target);r.camera.updateMatrixWorld();
r.canvas={getBoundingClientRect:()=>({left:0,top:0,width:100,height:100})};
assert.equal(r.pickBuilding(50,50)?.id,b.id);
const routeGraph=buildGraph(data,{distanceOnly:true});
const active=routeGraph.segments.find(x=>x.active&&x.d>5);assert.ok(active);
const near=(p,q,t)=>({x:p.x+(q.x-p.x)*t,z:p.z+(q.z-p.z)*t});
const from=near(active.a,active.b,.2),to=near(active.a,active.b,.8);
const before=findRoute(routeGraph,from,to,{maxSnap:1});assert.ok(before.length>0);
const after=buildGraph(data,{distanceOnly:true,blockedSegmentIds:[active.segmentId]});
assert.equal(after.segments.find(x=>x.segmentId===active.segmentId).active,false);
assert.equal(after.segments.find(x=>x.segmentId===active.segmentId).reason,'관리자가 연결한 차단 구간');
assert.ok(after.segments.filter(x=>x.active).length>0);
assert.ok(!Number.isNaN(toXY({lat:35.176,lng:126.907}).x));
console.log('PASS batched 3D building IDs/highlight 1,422 and exact hazard segment blocking');

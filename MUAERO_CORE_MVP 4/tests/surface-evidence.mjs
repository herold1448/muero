import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as THREE from '../vendor/three.module.js';
import {parseOSM,combine} from '../src/data.js';
import {CampusRenderer} from '../src/renderer.js';
import {buildGraph} from '../src/routing.js';
import {surfacePolygon,widthEvidence} from '../src/surface.js';

const read=p=>JSON.parse(fs.readFileSync(new URL(p,import.meta.url),'utf8'));
const rawPaths=read('../data/campus_paths.json'),rawBuildings=read('../data/campus_buildings.json');
const data=combine(parseOSM(rawPaths,{includeBuildings:false}),parseOSM(rawBuildings,{includePaths:false}));
assert.equal(data.ways.length,928);
assert.equal(data.ways.filter(w=>w.tags.footway==='sidewalk').length,364);
assert.equal(data.ways.filter(w=>w.tags.footway==='crossing').length,155);
assert.equal(data.ways.filter(w=>['service','residential','tertiary'].includes(w.tags.highway)).length,0);
assert.equal(fs.existsSync(new URL('../data/terrain/grid.json',import.meta.url)),false);
const p=surfacePolygon([{x:0,z:0},{x:10,z:0},{x:10,z:10}],2);
assert.equal(p[0].length,3);assert.ok(p.flat().every(q=>Number.isFinite(q.x)&&Number.isFinite(q.z)));
assert.equal(widthEvidence({tags:{}},{},'sidewalk',2.5).source.includes('추정'),true);
assert.equal(widthEvidence({tags:{width:'3 m'}},{},'sidewalk',2.5).metres,3);
const r=Object.create(CampusRenderer.prototype);for(const k of ['world','routeGroup','markerGroup','reportGroup','selectionGroup'])r[k]=new THREE.Group();r.terrain=null;r.start=null;r.end=null;
const routeCount=buildGraph(data).segments.length;
const nodes={'x1':{lat:35.174,lng:126.905},'x2':{lat:35.1741,lng:126.905}};
const roads={nodes,ways:[{id:'road-only',nodeIds:['x1','x2'],tags:{highway:'service'}}]};
r.load(data,{roads});
assert.equal(r.audit.renderedExtraRoads,1);assert.ok(r.audit.surfaceLayers.includes('sidewalk'));assert.ok(r.audit.surfaceLayers.includes('crossing'));assert.ok(r.audit.surfaceLayers.includes('carriageway'));
assert.equal(r.audit.terrainLoaded,false);assert.equal(r.audit.widthEvidence.measuredOrTagged,0);
assert.equal(buildGraph(data).segments.length,routeCount);
console.log('PASS OSM surface evidence, optional road render isolated from routing, missing DEM');
